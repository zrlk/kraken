#!/usr/bin/env python3
"""Writes Parse/ResetExitW.lean: `MmW`, `Mm` with the cells the footprint `RF` holds raw (the
frame, the pushes, `k[1..2]`, `n_master`, `f_master`) weakened to blocks, and `Mm_MmW`.

Usage: exit.py OUT_DIR
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import foot  # noqa: E402

R = "(t₀.regs.get64 .rsp)"
S = "(arg1 t₀)"

# atom -> (weakened expression, implication proof term `∀ m, X m → X' m`)
WEAK = {
    "fr": (f"0x548 ?@ ({R} - 0x578#64)", "val_imp hF (by decide)"),
    "saved": ("SavedB t₀", "saved_imp t₀"),
    "k1": (f"4 ?@ ({S} + 0x44#64)", "val_imp (Int.toBytes_length _ _) (by decide)"),
    "k2": (f"4 ?@ ({S} + 0x48#64)", "val_imp (Int.toBytes_length _ _) (by decide)"),
    "nm": (f"4 ?@ ({S} + 0x68#64)", "val_imp (Int.toBytes_length _ _) (by decide)"),
    "fm": (f"98 ?@ ({S} + 0x4c1f0#64)", "val_imp hfm (by decide)"),
}


def main():
  out_dir = sys.argv[1]
  names = [n for n, _, _ in foot.ATOMS]
  E = dict((n, e) for n, e, _ in foot.ATOMS)
  W = [WEAK[n][0] if n in WEAK else E[n] for n in names]
  P = [WEAK[n][1] if n in WEAK else "fun _ h => h" for n in names]
  term = f"({P[0]})"
  for p in P[1:]:
    term = f"(sep_imp {term} ({p}))"
  o = []
  p = o.append
  p("import Kraken.X64.Examples.Sbr.Parse.ResetIface")
  p("")
  p("/-!")
  p("# `sbr_reset`: the memory at the epilogue, weakened to the footprint's blocks")
  p("")
  p("Generated by `scripts/sbr/parse/reset/exit.py`.")
  p("-/")
  p("")
  p("open Kraken Kraken.SysV Mem Kraken.X64.Parser Std.WP MachineWP")
  p("open Kraken.Examples.Sbr Kraken.Examples.Sbr.Apply Kraken.Examples.Sbr.ParseModel")
  p("open Kraken.Examples.Sbr.Parse")
  p("")
  p("namespace Kraken.Examples.Sbr.Reset")
  p("")
  p("variable [CodeEnv]")
  p("")
  p("omit [CodeEnv] in")
  p("theorem sep_imp {P P' Q Q' : Mem 64 → Prop} (hp : ∀ m, P m → P' m) (hq : ∀ m, Q m → Q' m) :")
  p("    ∀ m, (P ⋆ Q) m → (P' ⋆ Q') m := by")
  p("  rintro m ⟨m1, m2, hu, hd, h1, h2⟩")
  p("  exact ⟨m1, m2, hu, hd, hp _ h1, hq _ h2⟩")
  p("")
  p("omit [CodeEnv] in")
  p("theorem val_imp {a : BitVec 64} {bs : List UInt8} {n : Nat} (hl : bs.length = n)")
  p("    (hw : n ≤ 2 ^ 64) : ∀ m, (bs =@ a) m → (n ?@ a) m :=")
  p("  fun _ h => ⟨hw, bs, hl, h⟩")
  p("")
  p("/-- The six pushes as 8-byte blocks. -/")
  p("def SavedB (t₀ : MachineData) : Mem 64 → Prop :=")
  p(f"  8 ?@ ({R} - 0x8#64) ⋆ (8 ?@ ({R} - 0x10#64) ⋆ (8 ?@ ({R} - 0x18#64)")
  p(f"    ⋆ (8 ?@ ({R} - 0x20#64) ⋆ (8 ?@ ({R} - 0x28#64) ⋆ 8 ?@ ({R} - 0x30#64)))))")
  p("")
  p("omit [CodeEnv] in")
  p("theorem saved_imp (t₀ : MachineData) : ∀ m, Saved t₀ m → SavedB t₀ m := by")
  p("  intro m h")
  p("  unfold Saved at h")
  p("  unfold SavedB")
  p("  exact sep_imp (val_imp (Int.toBytes_length _ _) (by decide)) (sep_imp")
  p("    (val_imp (Int.toBytes_length _ _) (by decide)) (sep_imp")
  p("    (val_imp (Int.toBytes_length _ _) (by decide)) (sep_imp")
  p("    (val_imp (Int.toBytes_length _ _) (by decide)) (sep_imp")
  p("    (val_imp (Int.toBytes_length _ _) (by decide))")
  p("    (val_imp (Int.toBytes_length _ _) (by decide)))))) m h")
  p("")
  p("/-- `Mm` with the raw cells of the footprint weakened to blocks. -/")
  p(f"def MmW {foot.B} : Mem 64 → Prop :=")
  p("  " + foot.wrap(foot.chain(W)))
  p("")
  p(f"theorem Mm_MmW {foot.B} (hF : FrOk fr) (hfm : st.fm.length = 98) :")
  p(f"    ∀ m, Mm {foot.A} m → MmW {foot.A} m := by")
  p("  intro m h")
  p("  unfold Mm at h")
  p("  unfold MmW")
  p(f"  exact {term} m h")
  p("")
  p("end Kraken.Examples.Sbr.Reset")
  p("")
  with open(os.path.join(out_dir, "ResetExitW.lean"), "w") as f:
    f.write("\n".join(o))


if __name__ == "__main__":
  main()
