#!/usr/bin/env python3
"""Writes Parse/ResetProc.lean: `sbr_reset`'s procedure theorem, assembled by
`ProcSpec.of_cfg_post` from the block theorems `blk_<id>` found in the given proof files; every
block without a theorem is a field of the hypothesis `ResetOpen k e` (its obligation, stated
exactly as a block theorem would); with no open block, `ResetOpen` and `ho` are omitted.

Block theorems: `theorem blk_<id> <params> : BlockOb k e a ra t₀ "<label>" ⟨…⟩`, the parameters
named from `k hk e hc hAv a ra t₀` (passed by name). A file containing `sorry` is skipped.
The proof files are read as staged (`git show :PATH`, run from the repository root), so
unstaged work in progress neither adds nor removes blocks; unstaged files are skipped.

Usage: proc.py BODY.s OUT_DIR PROOF.lean ...
"""
import os
import re
import subprocess
import sys

P = "sbr_reset"
ARGS = {"k": "k", "hk": "hk", "e": "e", "hc": "hc", "hAv": "hc.avlog", "a": "a", "ra": "ra",
        "t₀": "t₀"}


def staged(f):
  """The staged (index) content of `f`, or `None` if `f` is not in the index."""
  r = subprocess.run(["git", "show", f":./{f}"], capture_output=True)
  return r.stdout.decode() if r.returncode == 0 else None


def ident(lab):
  return "start" if lab == P else lab[len(P) + 1:]


def main():
  body, out_dir, proofs = sys.argv[1], sys.argv[2], sys.argv[3:]
  labels = []
  for line in open(body):
    m = re.match(r"^(sbr_reset[\w.]*):\s*$", line)
    if m:
      labels.append(m[1])
  have = {}
  mods = []
  for f in proofs:
    src = staged(f)
    if src is None:
      print(f"skip (not staged): {f}", file=sys.stderr)
      continue
    if src != open(f).read():
      print(f"warning: {f} differs from its staged version (lake builds the working copy)",
            file=sys.stderr)
    if re.search(r"\bsorry\b", src):
      print(f"skip (sorry): {f}", file=sys.stderr)
      continue
    found = False
    for m in re.finditer(r"theorem blk_(\w+)((?:\s*\([^()]*\))*)\s*:\s*BlockOb", src):
      params = re.findall(r"\(([^():]+?)\s*:", m[2])
      names = [n for grp in params for n in grp.split()]
      bad = [n for n in names if n not in ARGS]
      if bad:
        print(f"skip blk_{m[1]} ({f}): unknown params {bad}", file=sys.stderr)
        continue
      if m[1] in have:
        print(f"duplicate blk_{m[1]} ({f})", file=sys.stderr)
        continue
      have[m[1]] = names
      found = True
    if found:
      rel = os.path.relpath(f, os.path.join(out_dir, "..", "..", "..", "..", ".."))
      mods.append(rel[:-5].replace("/", "."))
  o = []
  p = o.append
  for mname in sorted(mods):
    p(f"import {mname}")
  p("")
  p("/-!")
  p("# `sbr_reset`: the procedure theorem")
  p("")
  p("Generated by `scripts/sbr/parse/reset/proc.py`: `ProcSpec.of_cfg_post` over the block list,")
  p("each block from its theorem `blk_<id>`; the blocks not proved here (if any) are the fields")
  p("of `ResetOpen` (open obligations, each stated as its block theorem would be).")
  p(f"Proved: {len([l for l in labels if ident(l) in have])} of {len(labels)} blocks.")
  p("-/")
  p("")
  p("open Kraken Kraken.SysV Mem Kraken.X64.Parser Std.WP MachineWP")
  p("open Kraken.Examples.Sbr Kraken.Examples.Sbr.Apply Kraken.Examples.Sbr.ParseModel")
  p("open Kraken.Examples.Sbr.Parse")
  p("")
  p("namespace Kraken.Examples.Sbr.Reset")
  p("")
  p("variable [CodeEnv]")
  p("")
  nxt = {l: (f'some "{labels[i + 1]}"' if i + 1 < len(labels) else "none")
         for i, l in enumerate(labels)}
  opened = [l for l in labels if ident(l) not in have]
  nopen = len(opened)
  if opened:
    p("/-- The open block obligations. -/")
    p("structure ResetOpen (k : Nat) (e : REnv) : Prop where")
    for l in opened:
      i = ident(l)
      p(f"  o_{i} : ∀ (a : RArgs) (ra : Int64) (t₀ : MachineData),")
      p(f"    BlockOb k e a ra t₀ \"{l}\" ⟨\"{l}\", B.{i}, {nxt[l]}⟩")
    p("")
  p("set_option maxRecDepth 100000 in")
  p("theorem spec (hpl : Program.PlacedIn body) (k : Nat) (hk : k ≤ 2 ^ 32) (e : REnv)")
  ho = " (ho : ResetOpen k e)" if opened else ""
  p(f"    (hc : ResetCallees k e){ho} : ResetSpec k e := by")
  p("  refine Kraken.Executable.ProcSpec.of_cfg_post (p := body) (table k e) (Post' k e) var")
  p("    (hblocks := ?_) (hpre := ?_) (hpost := ?_) (hwf := body_wf)")
  p("  · intro a ra t₀")
  p("    refine Program.forall_blockAt ?_")
  p("    rw [view_body]")
  p("    exact")
  terms = []
  for l in labels:
    i = ident(l)
    if i in have:
      args = " ".join(f"({n} := {ARGS[n]})" for n in have[i])
      terms.append(f"(blk_{i} {args})")
    else:
      terms.append(f"(ho.o_{i} a ra t₀)")
  for t in terms:
    p(f"      (.cons {t}")
  p("      (.nil _)" + ")" * len(terms))
  p("  · intro a ra t ht")
  p("    exact (T.start).mpr ⟨rfl, ht⟩")
  p("  · intro a ra t₀ s h; exact h")
  p("")
  p("end Kraken.Examples.Sbr.Reset")
  p("")
  with open(os.path.join(out_dir, "ResetProc.lean"), "w") as f:
    f.write("\n".join(o))
  print(f"{len(labels)} blocks, {len(labels) - nopen} proved, {nopen} open", file=sys.stderr)


if __name__ == "__main__":
  main()
