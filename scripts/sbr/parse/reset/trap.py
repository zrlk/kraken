#!/usr/bin/env python3
"""Writes Parse/ResetTrap.lean: the blocks whose table entry is `False` (the `ud1` traps, the
`av_assert0` path, the padding): each is proved from its entry.

Usage: trap.py BODY.s OUT_DIR
"""
import sys

P = "sbr_reset"
LABELS = ["L324d", "L3252", "L3257", "L325c", "L3261", "L3266", "L326b", "L3270", "L3275",
          "L327a", "L327f", "L3284", "L3289", "L328e", "L32af", "L32b4", "L32b9", "L32be",
          "L32c3", "L32c8", "L32cd", "L32d2", "L32d7", "L32dc", "L32ec"]


def main():
  labs = [l.strip()[:-1] for l in open(sys.argv[1]) if l.strip() and not l.startswith(" ")]
  ids = ["start" if l == P else l[len(P) + 1:] for l in labs]
  o = ["import Kraken.InfoOff",
       "import Kraken.X64.Examples.Sbr.Parse.ResetTable",
       "",
       "/-! # `sbr_reset`: the blocks with entry `False` (traps, `av_assert0`, padding)",
       "",
       "Generated by `scripts/sbr/parse/reset/trap.py`. -/",
       "",
       "open Kraken Kraken.SysV Mem Kraken.X64.Parser Std.WP MachineWP",
       "open Kraken.Examples.Sbr Kraken.Examples.Sbr.Apply Kraken.Examples.Sbr.ParseModel",
       "",
       "namespace Kraken.Examples.Sbr.Reset",
       "",
       "variable [CodeEnv]",
       ""]
  for l in LABELS:
    i = ids.index(l)
    nxt = f'some "{labs[i + 1]}"' if i + 1 < len(labs) else "none"
    o += [f"theorem blk_{l} (k : Nat) (e : REnv) (a : RArgs) (ra : Int64) (t₀ : MachineData) :",
          f'    BlockOb k e a ra t₀ "{P}.{l}" ⟨"{P}.{l}", B.{l}, {nxt}⟩ := by',
          "  info_off",
          f'  measure_hb "{l}"',
          "    intro n",
          "    refine Triple.pin fun s₀ hs₀ => ?_",
          f"    exact (T.{l}.mp hs₀.1).elim",
          ""]
  o.append("end Kraken.Examples.Sbr.Reset")
  open(f"{sys.argv[2]}/ResetTrap.lean", "w").write("\n".join(o) + "\n")


if __name__ == "__main__":
  main()
