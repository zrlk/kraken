#!/usr/bin/env python3
"""`sbr_reset`: the block-list text (`ResetBlocks.lean`, `ResetText.lean`) and the table
(`ResetTable.lean`).

Input: `body.s`, the output of `gen.py` (one label per block). The text is stated as its list
of blocks, each body a separate definition `B.<id>` (`Kraken/Rules/CfgTable.lean`), with the
label lemmas `L.<id>` and `I.<id>`. The table is position-indexed (`Program.LTable`): the entry
of block `<id>` is `E.<id>`, from the entry files `spec/*.py` (each defines `ENTRIES`, a dict
`id -> Lean text of a Prop in k e a ra t₀ s`, and optionally `VARS`, `id -> Lean list of the
inner variant digits` and `LEMMAS`, Lean text put before the entries). A block without an
entry gets `False`. The variant of a block is `lex (d0 :: inner)`, where `d0` is computed here:
the rank of the block's strongly connected component in the condensed control-flow graph
(edges between components strictly decrease it), and `inner` (default `[0, 0, 0]`) comes from
`VARS`; inside a component, a back edge must decrease `inner`.

Usage: table.py body.s OUTDIR
"""
import glob
import importlib.util
import os
import re
import sys

P = "sbr_reset"
NS = "Kraken.Examples.Sbr.Reset"
NINNER = 3
HERE = os.path.dirname(os.path.abspath(__file__))


def ident(lab):
  if lab == P:
    return "start"
  return lab[len(P) + 1:]


def read_blocks(path):
  blocks = []
  for l in open(path):
    l = l.rstrip("\n")
    if not l.strip():
      continue
    if not l.startswith(" "):
      blocks.append([l[:-1], []])
    else:
      blocks[-1][1].append(l.strip())
  return blocks


def succs(blocks):
  labs = [b[0] for b in blocks]
  out = {}
  for i, (lab, ins) in enumerate(blocks):
    s = []
    last = ins[-1] if ins else ""
    for t in ins:
      m = re.match(r"^j\w+\s+(\S+)$", t)
      if m and m[1].startswith(P):
        s.append(m[1])
    op = last.split()[0] if last else ""
    falls = not (op in ("jmp", "ret", "ud1") or last == "call abort")
    if falls and i + 1 < len(blocks):
      s.append(labs[i + 1])
    out[lab] = s
  return out


def sccs(nodes, g):
  idx, low, on, st, res, n = {}, {}, set(), [], [], [0]
  sys.setrecursionlimit(10000)

  def go(v):
    idx[v] = low[v] = n[0]; n[0] += 1; st.append(v); on.add(v)
    for w in g[v]:
      if w not in idx:
        go(w); low[v] = min(low[v], low[w])
      elif w in on:
        low[v] = min(low[v], idx[w])
    if low[v] == idx[v]:
      c = []
      while True:
        w = st.pop(); on.discard(w); c.append(w)
        if w == v:
          break
      res.append(c)
  for v in nodes:
    if v not in idx:
      go(v)
  return res


def ranks(blocks, g):
  nodes = [b[0] for b in blocks]
  comps = sccs(nodes, g)
  cid = {v: i for i, c in enumerate(comps) for v in c}
  # Tarjan emits components in reverse topological order: sinks first.
  rank = {}
  for i, c in enumerate(comps):
    r = 0
    for v in c:
      for w in g[v]:
        if cid[w] != i:
          r = max(r, rank[cid[w]] + 1)
    rank[i] = r
  loops = {v for c in comps if len(c) > 1 for v in c} | {v for v in nodes if v in g[v]}
  return {v: rank[cid[v]] for v in nodes}, loops


def load_specs():
  ents, vars_, lemmas = {}, {}, []
  for f in sorted(glob.glob(os.path.join(HERE, "spec", "*.py"))):
    spec = importlib.util.spec_from_file_location(os.path.basename(f)[:-3], f)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    for k, v in getattr(m, "ENTRIES", {}).items():
      assert k not in ents, f"entry {k} defined twice"
      ents[k] = v
    vars_.update(getattr(m, "VARS", {}))
    if getattr(m, "LEMMAS", ""):
      lemmas.append(m.LEMMAS)
  return ents, vars_, lemmas


TEXT_HEAD = """import Kraken.X64.Examples.Sbr.Parse.ResetBlocks
import Kraken.X64.Examples.Sbr.Parse.Lib
import Kraken.Rules.CfgTable
import Kraken.Rules.LexVar

/-!
# `sbr_reset`: the program text

The compiled `sbr_reset(ac, sbr)` of `libavcodec/aacsbr_template.c` (FFmpeg n8.1, `aacsbr.o`, see
`scripts/sbr/README.md`), with `sbr_make_f_master`, `make_bands`, `check_n_master`,
`sbr_make_f_derived`, `sbr_hf_calc_npatches` and `sbr_turnoff` inlined. Generated by
`scripts/sbr/parse/reset/gen.py` (labels of `to_program` plus cut points that keep a block at
about twelve instructions and two stores) and `table.py` (the text as its list of blocks, each
body a definition `B.<id>`, see `Kraken/Rules/CfgTable.lean`). Rip-relative operands carry their
symbol: `sbr_offset_r` is row `r` of `sbr_offset` (`.rodata+0x10+16*r`), `LCPI5_n` the
constants of `.rodata.cst*`, `L_str_n` the `av_log` format strings. The text itself (`B.<id>`,
`labelList`, `blocks`, `body`) is in `ResetBlocks.lean`; this module proves its label lemmas.
-/

open Kraken Kraken.X64.Parser

set_option mvcgen.warning false

namespace %s
""" % NS

BLOCKS_HEAD = """import Kraken.X64.Parser
import Kraken.Rules.CfgTable

/-!
# `sbr_reset`: the program text as its blocks

The text of `sbr_reset` (see `ResetText.lean`) as its list of blocks, each body a definition
`B.<id>` (`Kraken/Rules/CfgTable.lean`), with the labels in order. Generated by
`scripts/sbr/parse/reset/table.py`; imports only the parser and the machine model.
-/

open Kraken Kraken.X64.Parser

set_option mvcgen.warning false

namespace %s

namespace B
""" % NS


def blocks_text(blocks):
  o = [BLOCKS_HEAD]
  for lab, ins in blocks:
    o.append(f"def {ident(lab)} : Program := parse(\"\n" + "\n".join("    " + t for t in ins)
             + "\n\")")
  o.append("end B\n")
  o.append("/-- The labels, in order. -/\ndef labelList : List Label := [\n"
           + ",\n".join(f"  \"{b[0]}\"" for b in blocks) + "]\n")
  o.append("/-- The blocks, in order. -/\ndef blocks : List (Label × Program) := [\n"
           + ",\n".join(f"  (\"{b[0]}\", B.{ident(b[0])})" for b in blocks) + "]\n")
  o.append("""/-- The text of `sbr_reset`: the blocks glued with their labels. -/
def body : Program := blocks.flatMap Program.blockCells
""")
  o.append(f"end {NS}\n")
  return "\n".join(o)


def text(blocks, g):
  o = [TEXT_HEAD]
  o.append("""set_option maxRecDepth 200000 in
theorem blocks_free : ∀ lb ∈ blocks, ∀ d ∈ lb.2, d.isLabel = false := by decide +kernel

theorem view_body : Program.view body = ([], blocks) := Program.view_flatMap blocks blocks_free

set_option maxRecDepth 200000 in
theorem labels_body : Program.labels body = labelList := by
  rw [Program.labels_eq_view, view_body]; rfl

/-- A key per label (distinct keys, distinct labels: `labelList_nodup`). -/
def labelKey (s : String) : Nat := s.toList.foldl (fun n c => n * 256 + c.toNat) 0

set_option maxRecDepth 200000 in
theorem labelList_nodup : labelList.Nodup :=
  (List.pairwise_map.mp (show (labelList.map labelKey).Nodup by decide +kernel)).imp
    fun h e => h (congrArg labelKey e)

theorem body_wf : Program.WF body := ⟨labels_body ▸ labelList_nodup⟩

/-- The label questions of a jump to the `i`-th label. -/
theorem blockIdx_at {i : Nat} {l : Label} (h : labelList[i]? = some l) :
    Program.blockIdx body l = i :=
  Program.blockIdx_of_getElem? body_wf (labels_body ▸ h)

theorem isSome_at {i : Nat} {l : Label} (h : labelList[i]? = some l) :
    (Program.blockAt body l).isSome = true :=
  Program.isSome_blockAt_of_getElem? (labels_body ▸ h)

set_option maxRecDepth 100000

namespace L
""")
  for i, (lab, _) in enumerate(blocks):
    o.append(f"theorem {ident(lab)} : labelList[{i}]? = some \"{lab}\" := rfl")
  o.append("end L\n\nnamespace I")
  for i, (lab, _) in enumerate(blocks):
    o.append(f"@[lex_var] theorem {ident(lab)} : Program.blockIdx body \"{lab}\" = {i} := "
             f"blockIdx_at L.{ident(lab)}")
  o.append("end I\n\nnamespace S")
  for i, (lab, _) in enumerate(blocks):
    o.append(f"theorem {ident(lab)} : (Program.blockAt body \"{lab}\").isSome = true := "
             f"isSome_at L.{ident(lab)}")
  o.append(f"end S\n\nend {NS}\n")
  return "\n".join(o)


TABLE_HEAD = """import Kraken.X64.Examples.Sbr.Parse.ResetIface
import Kraken.X64.Examples.Sbr.Parse.LibQsort

/-!
# `sbr_reset`: the table

Generated by `scripts/sbr/parse/reset/table.py` from the entry files
`scripts/sbr/parse/reset/spec/*.py`. The table is position-indexed (`Program.LTable`): the
entry of the `i`-th label is `ENT[i]`; `T.<id>` rewrites the table at a literal label to its
entry. The variant of a label is `lex` of its digits: the rank of its loop (strongly connected
component) in the control-flow graph, then the loop's own measure.
-/

open Kraken Kraken.SysV Mem Kraken.X64.Parser Std.WP MachineWP
open Kraken.Examples.Sbr Kraken.Examples.Sbr.Apply Kraken.Examples.Sbr.ParseModel

set_option mvcgen.warning false

namespace %s

variable [CodeEnv]
""" % NS


def table(blocks, g, ents, vars_, lemmas):
  rk, loops = ranks(blocks, g)
  o = [TABLE_HEAD]
  o.extend(lemmas)
  o.append("namespace E")
  for lab, _ in blocks:
    i = ident(lab)
    o.append(f"/-- {lab} -/\nabbrev {i} (k : Nat) (e : REnv) (a : RArgs) (ra : Int64) "
             f"(t₀ : MachineData) : MachineData → Prop :=\n  fun s => {ents.get(i, 'False')}")
  o.append("end E\n")
  o.append("def ENT (k : Nat) (e : REnv) (a : RArgs) (ra : Int64) (t₀ : MachineData) :\n"
           "    List (MachineData → Prop) := [\n"
           + ",\n".join(f"  E.{ident(b[0])} k e a ra t₀" for b in blocks) + "]\n")
  o.append("""set_option maxRecDepth 100000

/-- The table: the entry of the `i`-th label is `ENT[i]`. -/
def table (k : Nat) (e : REnv) (a : RArgs) (ra : Int64) (t₀ : MachineData) (l : Label)
    (s : MachineData) : Prop :=
  Program.LTable labelList (ENT k e a ra t₀) l s

namespace T
""")
  for i, (lab, _) in enumerate(blocks):
    d = ident(lab)
    o.append(f"theorem {d} {{k e a ra t₀ s}} : table k e a ra t₀ \"{lab}\" s ↔ E.{d} k e a ra t₀ s"
             f" :=\n  Program.LTable.iff labelList_nodup (i := {i}) rfl rfl")
  o.append("end T\n\nnamespace VD")
  for lab, _ in blocks:
    d = ident(lab)
    inner = vars_.get(d, "[" + ", ".join(["0"] * NINNER) + "]")
    o.append(f"abbrev {d} : MachineData → List Nat := fun s => {rk[lab]} :: {inner}")
  o.append("end VD\n")
  o.append("def VAR : List (MachineData → List Nat) := [\n"
           + ",\n".join(f"  VD.{ident(b[0])}" for b in blocks) + "]\n")
  o.append("""/-- The variant: `lex` of the label's digits. -/
def var (l : Label) (s : MachineData) : Nat :=
  lex ((VAR[labelList.idxOf l]?.getD (fun _ => [])) s)

namespace V""")
  for i, (lab, _) in enumerate(blocks):
    d = ident(lab)
    o.append(f"@[lex_var] theorem {d} {{s : MachineData}} : var \"{lab}\" s = lex (VD.{d} s) := by\n"
             f"  rw [var, Program.idxOf_of_getElem? labelList_nodup (i := {i}) rfl]; rfl")
  o.append("end V\n")
  o.append("""/-- The obligation of the block `blk` at the literal label `l`. -/
abbrev BlockOb (k : Nat) (e : REnv) (a : RArgs) (ra : Int64) (t₀ : MachineData) (l : Label)
    (blk : Program.Block) : Prop :=
  ∀ n : Nat,
    ⦃ fun s => table k e a ra t₀ l s ∧ var l s = n ⦄ blk.body
    ⦃ (match blk.next with
       | some l' => fun _ s => table k e a ra t₀ l' s ∧ var l' s ≤ n
       | none => fun _ _ => False);
      fun a' s => Table.ofLabels (fun l' s => (Program.blockAt body l').isSome
          ∧ table k e a ra t₀ l' s ∧ Program.EdgeLt body var l n l' s) a' s
        ∨ (a' = ra ∧ Post' k e a ra t₀ s) ⦄
""")
  o.append(f"end {NS}\n")
  return "\n".join(o), rk, loops


def main():
  blocks = read_blocks(sys.argv[1])
  out = sys.argv[2]
  g = succs(blocks)
  open(os.path.join(out, "ResetBlocks.lean"), "w").write(blocks_text(blocks))
  open(os.path.join(out, "ResetText.lean"), "w").write(text(blocks, g))
  ents, vars_, lemmas = load_specs()
  unknown = set(ents) - {ident(b[0]) for b in blocks}
  assert not unknown, unknown
  t, rk, loops = table(blocks, g, ents, vars_, lemmas)
  open(os.path.join(out, "ResetTable.lean"), "w").write(t)
  # a summary: id, rank, in a loop, successors
  with open(os.path.join(HERE, "blocks.txt"), "w") as f:
    for lab, ins in blocks:
      f.write(f"{ident(lab):10} r={rk[lab]:3} {'loop' if lab in loops else '    '} "
              f"n={len(ins):3} -> {' '.join(ident(x) for x in g[lab])}\n")


main()
