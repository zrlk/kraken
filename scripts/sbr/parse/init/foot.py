#!/usr/bin/env python3
"""Footprint of `ff_aac_sbr_ctx_alloc_init` for `Parse/InitFoot.lean`.

The element `ExtChannelElement` (0x88ba0 bytes at `p`, from `av_mallocz`) as a separating
conjunction of cells in address order: the zero runs (`zs n`) and the cells the routine writes or
hands to a callee (byte lists, fields of `EV`). Emits `EV`, `ev0`, `ElemS`, one hole `ElemH_x`
and one equation `ElemS_x : ElemS p v = v.x =@ (p + off) ⋆ ElemH_x p v` per field (and the
pairs `ana`, `syn`), and the split of the zeroed block `zs_elemS`.

The two definitions the final statement mentions, `EV` and `ElemS`, are specification: they
live in `SessionSpec.lean` (the section of `Parse/InitFoot.lean`), and `foot.py --spec` prints them as they
stand there (`ci.sh`, step `spec`, compares); the rest (`ev0`, `EV.ok`,
the `ElemH_x` holes and the lemmas) is `Parse/InitFoot.lean`.

Usage: foot.py > Kraken/X64/Examples/Sbr/Parse/InitFoot.lean
       foot.py --spec   (the `EV`/`ElemS` text of SessionSpec.lean)
"""
import sys

SEGS = [
    ("z", 0x0, 0x9e40), ("pr0", 0x9e40, 8), ("z", 0x9e48, 0x9db8), ("pr1", 0x13c00, 8),
    ("z", 0x13c08, 0x14d1c), ("sr", 0x28924, 8), ("id", 0x2892c, 4), ("usac", 0x28930, 4),
    ("z", 0x28934, 8), ("spLo", 0x2893c, 4), ("spHi", 0x28940, 2), ("z", 0x28942, 0x32),
    ("kx0", 0x28974, 4), ("kx1", 0x28978, 4), ("z", 0x2897c, 4), ("m1", 0x28980, 4),
    ("z", 0x28984, 0x391c), ("v0", 0x2c2a0, 4), ("z", 0x2c2a4, 4), ("e0", 0x2c2a8, 4),
    ("z", 0x2c2ac, 0x15ab4), ("v1", 0x41d60, 4), ("z", 0x41d64, 4), ("e1", 0x41d68, 4),
    ("z", 0x41d6c, 0x32d4c), ("ps", 0x74ab8, 0x40), ("z", 0x74af8, 0x13fe8),
    ("anaC", 0x88ae0, 8), ("anaF", 0x88ae8, 8), ("synC", 0x88af0, 8), ("synF", 0x88af8, 8),
    ("dsp", 0x88b00, 0x70), ("c0", 0x88b70, 8), ("c1", 0x88b78, 8), ("c2", 0x88b80, 8),
    ("c3", 0x88b88, 8), ("z", 0x88b90, 0x10),
]
TOTAL = 0x88ba0

DOC = {
    "pr0": "`ch.ch[0].predictor_state` (`ChannelElement`)",
    "pr1": "`ch.ch[1].predictor_state`",
    "sr": "`sbr->start`, `sbr->ready_for_dequant` (one 8-byte store)",
    "id": "`sbr->id_aac`", "usac": "`sbr->usac`",
    "spLo": "`sbr->spectrum_params`, bytes 0..3", "spHi": "`sbr->spectrum_params`, bytes 4..5",
    "kx0": "`sbr->kx[0]`", "kx1": "`sbr->kx[1]`", "m1": "`sbr->m[1]`",
    "v0": "`sbr->data[0].synthesis_filterbank_samples_offset`", "e0": "`sbr->data[0].e_a[1]`",
    "v1": "`sbr->data[1].synthesis_filterbank_samples_offset`", "e1": "`sbr->data[1].e_a[1]`",
    "ps": "`sbr->ps.dsp` (`PSDSPContext`, 64 bytes)",
    "anaC": "`sbr->mdct_ana`", "anaF": "`sbr->mdct_ana_fn`",
    "synC": "`sbr->mdct`", "synF": "`sbr->mdct_fn`",
    "dsp": "`sbr->dsp` (`SBRDSPContext`, 0x70 bytes)",
    "c0": "`sbr->c.sbr_lf_gen`", "c1": "`sbr->c.sbr_hf_assemble`",
    "c2": "`sbr->c.sbr_x_gen`", "c3": "`sbr->c.sbr_hf_inverse_filter`",
}

FIELDS = [(n, a, l) for n, a, l in SEGS if n != "z"]
PAIRS = {"ana": ["anaC", "anaF"], "syn": ["synC", "synF"]}


def addr(a):
  return "p" if a == 0 else f"(p + {hex(a)}#64)"


def atom(n, a, l):
  if n == "z":
    return f"zs {hex(l)} =@ {addr(a)}"
  return f"v.{n} =@ {addr(a)}"


def sep(xs):
  s = xs[-1]
  for x in reversed(xs[:-1]):
    s = f"{x} ⋆ ({s})" if " ⋆ " in s else f"{x} ⋆ {s}"
  return s


def wrap(head, s, ind="  ", cont="    ", width=100):
  """`head` then the sum `s` broken at ` ⋆ ` into lines of at most `width` characters."""
  out, cur = [head], ind
  for i, x in enumerate(s.split(" ⋆ ")):
    tok = x if i == 0 else "⋆ " + x
    if cur.strip() and len(cur) + 1 + len(tok) > width:
      out.append(cur)
      cur = cont + tok
    else:
      cur = cur + (" " if cur.strip() else "") + tok
  out.append(cur)
  return out


def spec_text():
  """`EV` and `ElemS` (in `SessionSpec.lean`)."""
  P = []
  p = P.append
  p("/-- The bytes of the cells the routine writes or hands to a callee. -/")
  p("structure EV where")
  for n, a, l in FIELDS:
    p(f"  /-- {DOC[n]} ({l} bytes at `p + {hex(a)}`). -/")
    p(f"  {n} : List UInt8")
  p("")
  p("/-- The element at `p` with the cells `v`. -/")
  P.extend(wrap("def ElemS (p : BitVec 64) (v : EV) : Mem 64 → Prop :=",
                sep([atom(*s) for s in SEGS])))
  return P


def main():
  if "--spec" in sys.argv:
    print("\n".join(spec_text()))
    return
  o = 0
  for n, a, l in SEGS:
    assert a == o, (n, hex(a), hex(o))
    o = a + l
  assert o == TOTAL
  P = []
  p = P.append
  p("import Kraken.X64.Examples.Sbr.Parse.InitText")
  p("import Kraken.X64.Examples.Sbr.Parse.Lib")
  p("import Kraken.X64.Examples.Sbr.ApplySpec")
  p("import Kraken.X64.Examples.Sbr.Session")
  p("import Kraken.X64.Examples.Sbr.SessionSpec")
  p("")
  p("/-!")
  p("# `ff_aac_sbr_ctx_alloc_init`: the element as cells")
  p("")
  p("Generated by `scripts/sbr/parse/init/foot.py`. The `ExtChannelElement` that `av_mallocz`")
  p("returns (0x88ba0 bytes at `p`; `sbr` at `p + 0x28920`) as cells in address order: the zero")
  p("runs and the cells the routine writes or hands to a callee (the fields of `EV`, byte lists).")
  p("`ElemS_x` brings the cell of field `x` to the front (`ElemH_x`: the other cells, which do not")
  p("depend on `v.x`); `zs_elemS` splits the zeroed block. `EV` and `ElemS` are in")
  p("`SessionSpec.lean` (`foot.py --spec`).")
  p("-/")
  p("")
  p("open Kraken Kraken.SysV Mem Kraken.X64.Parser Std.WP MachineWP")
  p("open Kraken.Examples.Sbr.Session (zs)")
  p("")
  p("namespace Kraken.Examples.Sbr.Init")
  p("")
  p("/-- All zero (the element as `av_mallocz` returns it). -/")
  p("def ev0 : EV where")
  for n, a, l in FIELDS:
    p(f"  {n} := zs {hex(l)}")
  p("")
  p("/-- The cell lengths. -/")
  p("def EV.ok (v : EV) : Prop :=")
  p("  " + " ∧ ".join(f"v.{n}.length = {hex(l)}" for n, a, l in FIELDS))
  p("")
  targets = [(n, [n]) for n, a, l in FIELDS] + list(PAIRS.items())
  for t, fs in targets:
    rest = [atom(*s) for s in SEGS if s[0] not in fs]
    p(f"/-- `ElemS` without {', '.join('`' + f + '`' for f in fs)}. -/")
    p(f"def ElemH_{t} (p : BitVec 64) (v : EV) : Mem 64 → Prop :=")
    p("  " + sep(rest))
    p("")
    front = [atom(*s) for s in SEGS if s[0] in fs]
    p(f"theorem ElemS_{t} (p : BitVec 64) (v : EV) :")
    p(f"    ElemS p v = {sep(front + [f'ElemH_{t} p v'])} := by")
    p(f"  unfold ElemS ElemH_{t}; ac_rfl")
    p("")
  # access lemmas
  p("section Access")
  p("")
  p("variable {m : Mem 64} {p : BitVec 64} {v : EV} {F : Mem 64 → Prop}")
  p("")
  for n, a, l in FIELDS:
    A = f"(p + {hex(a)}#64)"
    p(f"theorem ElemS_st_{n} (h : m =⋆ ElemS p v ⋆ F) (hl : v.{n}.length = {l}) (w : Int) :")
    p(f"    m.storeInt {A} {l} w =⋆ ElemS p {{ v with {n} := Int.toBytes {l} w }} ⋆ F := by")
    p(f"  rw [ElemS_{n}, Std.ExtHashMap.sep_assoc] at h")
    p(f"  rw [ElemS_{n}, Std.ExtHashMap.sep_assoc]")
    p(f"  exact Val.storeInt h (Split.here _ _) hl w")
    p("")
    p(f"theorem ElemS_ld_{n} (h : m =⋆ ElemS p v ⋆ F) (hl : v.{n}.length = {l}) :")
    p(f"    m.loadInt {A} {l} = some (Int.ofBytes v.{n}) := by")
    p(f"  rw [ElemS_{n}, Std.ExtHashMap.sep_assoc] at h")
    p(f"  exact Val.loadInt h (Split.here _ _) hl (by decide)")
    p("")
    p(f"theorem ElemS_out_{n} (h : m =⋆ ElemS p v ⋆ F) (hl : v.{n}.length = {l}) :")
    p(f"    m =⋆ {l} ?@ {A} ⋆ (ElemH_{n} p v ⋆ F) := by")
    p(f"  rw [ElemS_{n}, Std.ExtHashMap.sep_assoc] at h")
    p(f"  have h' := Val.forget h (Split.here _ _) (by rw [hl]; decide)")
    p(f"  rw [hl] at h'; exact h'")
    p("")
    p(f"theorem ElemS_in_{n} (h : m =⋆ {l} ?@ {A} ⋆ (ElemH_{n} p v ⋆ F)) :")
    p(f"    ∃ bs : List UInt8, bs.length = {l} ∧ m =⋆ ElemS p {{ v with {n} := bs }} ⋆ F := by")
    p(f"  obtain ⟨-, bs, hlen, h'⟩ := Block.sep_elim h")
    p(f"  refine ⟨bs, hlen, ?_⟩")
    p(f"  rw [ElemS_{n}, Std.ExtHashMap.sep_assoc]")
    p(f"  exact h'")
    p("")
  for t, (f1, f2) in PAIRS.items():
    a1 = dict((n, a) for n, a, l in FIELDS)[f1]
    a2 = dict((n, a) for n, a, l in FIELDS)[f2]
    A1, A2 = f"(p + {hex(a1)}#64)", f"(p + {hex(a2)}#64)"
    p(f"theorem ElemS_out_{t} (h : m =⋆ ElemS p v ⋆ F) (h1 : v.{f1}.length = 8)")
    p(f"    (h2 : v.{f2}.length = 8) : m =⋆ 8 ?@ {A1} ⋆ (8 ?@ {A2} ⋆ (ElemH_{t} p v ⋆ F)) := by")
    p(f"  rw [ElemS_{t}, Std.ExtHashMap.sep_assoc, Std.ExtHashMap.sep_assoc] at h")
    p(f"  have h' := Val.forget h (Split.here _ _) (by rw [h1]; decide)")
    p(f"  rw [h1, Std.ExtHashMap.sep_comm_l] at h'")
    p(f"  have h'' := Val.forget h' (Split.here _ _) (by rw [h2]; decide)")
    p(f"  rw [h2] at h''")
    p(f"  rw [Std.ExtHashMap.sep_comm_l] at h''")
    p(f"  exact h''")
    p("")
    p(f"theorem ElemS_in_{t} {{b1 b2 : List UInt8}}")
    p(f"    (h : m =⋆ b1 =@ {A1} ⋆ (b2 =@ {A2} ⋆ (ElemH_{t} p v ⋆ F))) :")
    p(f"    m =⋆ ElemS p {{ v with {f1} := b1, {f2} := b2 }} ⋆ F := by")
    p(f"  rw [ElemS_{t}, Std.ExtHashMap.sep_assoc, Std.ExtHashMap.sep_assoc]")
    p(f"  exact h")
    p("")
  p("end Access")
  p("")
  # zero split
  p("theorem zs_add (n k : Nat) : zs (n + k) = zs n ++ zs k := (List.replicate_append_replicate ..).symm")
  p("")
  p("theorem zs_len (n : Nat) : (zs n).length = n := List.length_replicate ..")
  p("")
  p("/-- A zero run at `p + o` split at `n`. -/")
  p("theorem zs_split (p : BitVec 64) (o n k : Nat) (h : n + k ≤ 2 ^ 64) :")
  p("    zs (n + k) =@ (p + BitVec.ofNat 64 o)")
  p("      = zs n =@ (p + BitVec.ofNat 64 o) ⋆ zs k =@ (p + BitVec.ofNat 64 (o + n)) := by")
  p("  rw [zs_add, Val.append_eq (zs n) (zs k) _ _ ?_ (by rw [zs_len, zs_len]; exact h)]")
  p("  rw [zs_len, BitVec.add_assoc, BitVec.ofNat_add]")
  p("")
  p("/-- A zero run at `p` split at `n`. -/")
  p("theorem zs_split0 (p : BitVec 64) (n k : Nat) (h : n + k ≤ 2 ^ 64) :")
  p("    zs (n + k) =@ p = zs n =@ p ⋆ zs k =@ (p + BitVec.ofNat 64 n) := by")
  p("  rw [zs_add, Val.append_eq (zs n) (zs k) _ _ ?_ (by rw [zs_len, zs_len]; exact h)]")
  p("  rw [zs_len]")
  p("")
  p("/-- The zeroed element is `ElemS` at `ev0`. -/")
  p("theorem zs_elemS (p : BitVec 64) : zs 0x88ba0 =@ p = ElemS p ev0 := by")
  rem = TOTAL
  for i, (n, a, l) in enumerate(SEGS[:-1]):
    lem = f"zs_split0 p {hex(l)} {hex(rem - l)}" if i == 0 else \
        f"zs_split p {hex(a)} {hex(l)} {hex(rem - l)}"
    p(f"  rw [show ({hex(rem)} : Nat) = {hex(l)} + {hex(rem - l)} from rfl, {lem} (by decide)]")
    p("  try simp only [Nat.reduceAdd]")
    rem -= l
  p("  rfl")
  p("")
  p("end Kraken.Examples.Sbr.Init")
  print("\n".join(P))


main()
