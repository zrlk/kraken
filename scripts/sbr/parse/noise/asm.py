#!/usr/bin/env python3
"""The assembly of `read_sbr_noise` (`Parse/NoiseProc.lean`) from its labels.

Input: the program body (`gen.py` output). Output (stdout): the Lean file. Every label of the
body gets its block obligation either from a proved theorem (every `theorem blk_LXXXX … :
BlockOb …` in `Parse/NoiseBlk*.lean`, applied to its explicit binders by name) or from a field
of the structure `NoiseOpen` (the open obligations, one per label). The entry and exit
conversions are fields too unless `noise_pre`/`noise_post` are proved in a `NoiseBlk*` file.

Usage: asm.py BODY.s > Kraken/X64/Examples/Sbr/Parse/NoiseProc.lean
"""
import glob
import os
import re
import sys

P = "read_sbr_noise"
PARSE = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "../../../../Kraken/X64/Examples/Sbr/Parse")
PROVED = {}
CONV = {}
MODS = []
for f in sorted(glob.glob(os.path.join(PARSE, "NoiseBlk*.lean"))):
  mod = os.path.basename(f)[:-5]
  txt = open(f).read()
  MODS.append(mod)
  for m in re.finditer(r"^theorem (blk_(L\w+|entry|done))(.*?)BlockOb", txt, re.M | re.S):
    names = []
    for b in re.finditer(r"\(([^():]+?) :", m.group(3)):
      names += b.group(1).split()
    s = m.group(2)
    PROVED["" if s == "entry" else s] = (m.group(1), " ".join(names))
  for nm in ("noise_pre", "noise_post"):
    if re.search(rf"^theorem {nm}\b", txt, re.M):
      CONV[nm] = True
# open blocks that call a contract: the field takes it
CALLEE = {"L6667": ("AvLogSpec Ext k", "hAv")}

HEAD = '''import Kraken.X64.Examples.Sbr.Parse.NoiseMem
IMPORTS
-- Generated by scripts/sbr/parse/noise/asm.py. Do not edit.

/-!
# `read_sbr_noise`: the assembly

`spec`: `read_sbr_noise` meets `NoiseSpec` (`NoisePre`/`NoisePost`), from the block obligations
of `table`/`var` (`NoiseBase.lean`). The obligations proved so far are used directly; the open
ones are the fields of `NoiseOpen` (with the entry and exit conversions `pre`/`post` while
those are open). The callee contract: `av_log` (`AvLogSpec`).
-/

open Kraken Kraken.SysV Mem Kraken.X64.Parser Std.WP MachineWP
open Kraken.Examples.Sbr Kraken.Examples.Sbr.Apply

namespace Kraken.Examples.Sbr.Noise

variable [CodeEnv]

'''


def field(s):
  return "entry" if s == "" else s


def main():
  labs = []
  for l in open(sys.argv[1]):
    if l.strip() and not l.startswith(" "):
      labs.append(l.strip()[:-1])
  suf = [l[len(P) + 1:] if l != P else "" for l in labs]
  out = [HEAD.replace("IMPORTS\n", "".join(
      f"import Kraken.X64.Examples.Sbr.Parse.{m}\n" for m in MODS), 1)]
  out.append("/-- The labels of `body`, in order. -/")
  out.append("def noiseLabels : List Label := [")
  out.append(",\n".join(f'  "{l}"' for l in labs) + "]")
  out.append("")
  out.append("omit [CodeEnv] in")
  out.append("theorem labels_body : Program.labels body = noiseLabels := by decide +kernel")
  out.append("")
  out.append("/-- The open obligations: the blocks not yet proved, and the conversions between")
  out.append("`NoisePre`/`NoisePost` and the table's entry/`Post'`. -/")
  out.append("structure NoiseOpen (k : Nat) (Ext : Mem 64 → Prop) : Prop where")
  n_open = 0
  for l, s in zip(labs, suf):
    if s not in PROVED:
      c = CALLEE[s][0] + " → " if s in CALLEE else ""
      out.append(f'  {field(s)} : {c}∀ x ra t₀, BlockOb k Ext x ra t₀ "{l}"')
      n_open += 1
  if "noise_pre" not in CONV:
    out.append(f"  pre : ∀ x ra t, NoisePre k Ext x ra t → table k Ext x ra t \"{P}\" t")
    n_open += 1
  if "noise_post" not in CONV:
    out.append("  post : ∀ x ra t₀ s, Post' k Ext x ra t₀ s → NoisePost k Ext x ra t₀ s")
    n_open += 1
  if n_open == 0:
    out.append("  done : True")
  out.append("")
  out.append('''/-- `read_sbr_noise` meets `NoiseSpec`, given the open obligations. -/
theorem spec (hpl : Program.PlacedIn body) (k : Nat) HK(Ext : Mem 64 → Prop)
    (hAv : AvLogSpec Ext k) (hO : NoiseOpen k Ext) : NoiseSpec k Ext := by
  refine Kraken.Executable.ProcSpec.of_cfg_post (p := body) (table k Ext) (Post' k Ext) var
    (hblocks := ?_) (hpre := PRE) (hpost := POST)
  intro x ra t₀ l blk hblk
  have hl := Program.blockAt_mem_labels hblk
  rw [labels_body] at hl
  simp only [noiseLabels, List.mem_cons, List.not_mem_nil, or_false] at hl''')
  out[-1] = out[-1].replace("PRE", "(noise_pre k Ext)" if "noise_pre" in CONV else "hO.pre").replace(
      "POST", "(noise_post k hk Ext)" if "noise_post" in CONV else "hO.post").replace(
      "HK", "(hk : k ≤ 2 ^ 32) " if "noise_post" in CONV else "")
  out.append("  rcases hl with " + " | ".join(["rfl"] * len(labs)))
  for l, s in zip(labs, suf):
    if s in PROVED:
      n, a = PROVED[s]
      out.append(f"  · exact {n} {a} blk hblk")
    else:
      c = CALLEE[s][1] + " " if s in CALLEE else ""
      out.append(f"  · exact hO.{field(s)} {c}x ra t₀ blk hblk")
  out.append("")
  out.append("end Kraken.Examples.Sbr.Noise")
  print("\n".join(out))


main()
