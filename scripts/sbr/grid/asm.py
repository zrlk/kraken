#!/usr/bin/env python3
"""The assembly of `read_sbr_grid` (`Parse/GridAsm.lean`) from its labels.

Input: the program body (`gen.py` output). Output (stdout): the Lean file. Every label of the
body gets its block obligation either from a proved theorem (PROVED below: label suffix ->
the theorem applied to its arguments) or from a field of the structure `GridOpen` (the open
obligations, one per label). When a block gets proved, add it to PROVED and regenerate.

Usage: asm.py BODY.s > Kraken/X64/Examples/Sbr/Parse/GridAsm.lean
"""
import glob
import os
import re
import sys

P = "read_sbr_grid"
STD = "k hk Ext x ra t₀"
AV = "k hk Ext hAv x ra t₀"
MS = "k hk Ext hMs x ra t₀"
TRAP = "k Ext x ra t₀"
PROVED = {
    "": ("blk_entry", STD), "L440b": ("blk_L440b", STD), "L4419": ("blk_L4419", STD),
    "L4422": ("blk_L4422", STD), "L442b": ("blk_L442b", STD), "L4434": ("blk_L4434", STD),
    "L443a": ("blk_L443a", STD), "L4478": ("blk_L4478", STD), "L448b": ("blk_L448b", STD),
    "L4cb0": ("blk_L4cb0", STD), "L4cc9": ("blk_L4cc9", STD),
    "L4ec4": ("blk_L4ec4", STD), "L4ecc": ("blk_L4ecc", AV), "L4ed3": ("blk_L4ed3", STD),
    "L506f": ("blk_L506f", AV), "L5086": ("blk_L5086", STD), "L508b": ("blk_L508b", STD),
    "done": ("blk_done", STD),
}
for a in ["4a37", "4a6b", "4a85", "4ab9", "4ad3", "4b07", "4b21", "4b55", "4b6b", "4b9f",
          "4f51", "506a", "50ca", "50cf", "50d4", "50d9", "50de", "50e3", "5113", "5118",
          "511d", "5122", "5127", "512c", "5131", "5136", "513b"]:
  PROVED["L" + a] = ("blk_L" + a, TRAP)
# sample blocks (Parse/GridSmp.lean)
SMP = ["4ca9", "510e", "4fae", "4f93"]
for a in SMP:
  PROVED["L" + a] = ("blk_L" + a, STD)
# shard files (Parse/GridSh*.lean): every `theorem blk_LXXXX … : BlockOb …` found there is used,
# applied to its explicit binders by name (`k hk Ext x ra t₀`, plus `hAv`/`hMs` when it calls)
PARSE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../Kraken/X64/Examples/Sbr/Parse")
# only the shard modules reported as landed (a landed module must stay green)
LANDED = ["GridShA1", "GridShA2", "GridShA3", "GridShA4", "GridShA5", "GridShA6", "GridShA7", "GridShA8", "GridShB1", "GridShB2", "GridShB3", "GridShB4", "GridShC1", "GridShC2", "GridShC3", "GridShD1", "GridShD2", "GridShD3", "GridShD4", "GridShD5", "GridShD6", "GridShD7", "GridShD8", "GridShD9", "GridShD10"]
SHARDS = []
CONV = {}  # `grid_pre`/`grid_post (k) (Ext)` proved in a shard: replaces the field
for f in sorted(glob.glob(os.path.join(PARSE, "GridSh*.lean"))):
  mod = os.path.basename(f)[:-5]
  if mod not in LANDED:
    continue
  txt = open(f).read()
  code = re.sub(r"--[^\n]*", "", re.sub(r"/-.*?-/", "", txt, flags=re.S))
  if re.search(r"\bsorry\b|\badmit\b|^\s*axiom\b", code, re.M):
    sys.exit(f"asm.py: landed module {mod} contains sorry/admit/axiom: refusing")
  found = False
  for m in re.finditer(r"^theorem (blk_L(\w+))(.*?)BlockOb", txt, re.M | re.S):
    names = []
    for b in re.finditer(r"\(([^():]+?) :", m.group(3)):
      names += b.group(1).split()
    PROVED["L" + m.group(2)] = (m.group(1), " ".join(names))
    found = True
  for nm in ("grid_pre", "grid_post"):
    if re.search(rf"^theorem {nm}\b", txt, re.M):
      CONV[nm] = True
      found = True
  if found:
    SHARDS.append(mod)
# name clashes between shard modules (all are imported together): report on stderr
_seen = {}
for f in sorted(glob.glob(os.path.join(PARSE, "Grid*.lean"))):
  mod = os.path.basename(f)[:-5]
  if mod.startswith("GridSh") and mod not in LANDED:
    continue
  for m in re.finditer(r"^(?:private )?(?:theorem|def|abbrev|lemma) (\S+)", open(f).read(), re.M):
    if m.group(0).startswith("private"):
      continue
    if m.group(1) in _seen and _seen[m.group(1)] != mod:
      print(f"asm.py: `{m.group(1)}` in both {_seen[m.group(1)]} and {mod}", file=sys.stderr)
    _seen.setdefault(m.group(1), mod)
# open blocks that call a contract: the field takes it
CALLEE = {"L4dcb": ("MemsetValSpec k", "hMs"), "L50e8": ("AvLogSpec Ext k", "hAv")}

HEAD = '''import Kraken.X64.Examples.Sbr.Parse.LibCall
import Kraken.X64.Examples.Sbr.Parse.GridBlk1
import Kraken.X64.Examples.Sbr.Parse.GridBlk2
import Kraken.X64.Examples.Sbr.Parse.GridBlk3
import Kraken.X64.Examples.Sbr.Parse.GridBlk4
import Kraken.X64.Examples.Sbr.Parse.GridTrap

-- Generated by scripts/sbr/grid/asm.py. Do not edit.

/-!
# `read_sbr_grid`: the assembly

`spec`: `read_sbr_grid` meets `GridPre`/`GridPost` or reaches `abort` (`ProcSpecA`), from the
block obligations of `table`/`var` (`GridBase.lean`). The obligations proved so far are used
directly; the open ones are the fields of `GridOpen` (with the entry and exit conversions
`pre`/`post`). The callee contracts: `av_log` (`AvLogSpec`), `memset` (`MemsetValSpec`).
-/

open Kraken Kraken.SysV Mem Kraken.X64.Parser Std.WP MachineWP
open Kraken.Examples.Sbr Kraken.Examples.Sbr.Apply Kraken.Examples.Sbr.Parse

namespace Kraken.Examples.Sbr.Grid

variable [CodeEnv]

'''


def main():
  labs = []
  for l in open(sys.argv[1]):
    if l.strip() and not l.startswith(" "):
      labs.append(l.strip()[:-1])
  suf = [l[len(P) + 1:] if l != P else "" for l in labs]
  imps = (["GridSmp"] if SMP else []) + SHARDS
  out = [HEAD.replace("GridTrap\n", "GridTrap\n" + "".join(
      f"import Kraken.X64.Examples.Sbr.Parse.{m}\n" for m in imps), 1)]
  out.append("/-- The labels of `body`, in order. -/")
  out.append("def gridLabels : List Label := [")
  out.append(",\n".join(f'  "{l}"' for l in labs) + "]")
  out.append("")
  out.append("omit [CodeEnv] in")
  out.append("theorem labels_body : Program.labels body = gridLabels := by decide +kernel")
  out.append("")
  out.append("omit [CodeEnv] in")
  out.append("theorem body_wf : Program.WF body := ⟨labels_body ▸ (by decide +kernel)⟩")
  out.append("")
  nopen = sum(1 for s in suf if s not in PROVED) + ("grid_pre" not in CONV) + ("grid_post" not in CONV)
  if nopen:
    out.append("/-- The open obligations: the blocks not yet proved, and the conversions between")
    out.append("`GridPre`/`GridPost` and the table's entry/`Post'`. -/")
    out.append("structure GridOpen (k : Nat) (Ext : Mem 64 → Prop) : Prop where")
  for l, s in zip(labs, suf):
    if s not in PROVED:
      c = CALLEE[s][0] + " → " if s in CALLEE else ""
      out.append(f'  {s} : {c}∀ x ra t₀, BlockOb k Ext x ra t₀ "{l}"')
  if "grid_pre" not in CONV:
    out.append("  pre : ∀ x ra t, GridPre k Ext x ra t → table k Ext x ra t \"read_sbr_grid\" t")
  if "grid_post" not in CONV:
    out.append("  post : ∀ x ra t₀ s, Post' k Ext x ra t₀ s → GridPost k Ext x ra t₀ s")
  out.append("")
  out.append('''/-- `read_sbr_grid` meets its contract or reaches `abort`, given the open obligations. -/
theorem spec (hpl : Program.PlacedIn body) (k : Nat) (hk : k ≤ 2 ^ 32) (Ext : Mem 64 → Prop)
    (hAv : AvLogSpec Ext k) (hMs : MemsetValSpec k) (hO : GridOpen k Ext) :
    ProcSpecA ((_root_.Executable.labels cenv).label "read_sbr_grid")
      (fun x ra t => GridPre k Ext x ra t) (fun x ra t s => GridPost k Ext x ra t s) := by
  refine ProcSpecA.of_cfg_post (p := body) (fun x ra t₀ => table k Ext x ra t₀)
    (fun x ra t₀ => Post' k Ext x ra t₀) var ?_ PRE POST (hwf := body_wf)
  intro x ra t₀ l blk hblk
  have hl := Program.blockAt_mem_labels hblk
  rw [labels_body] at hl
  simp only [gridLabels, List.mem_cons, List.not_mem_nil, or_false] at hl''')
  if not nopen:
    out[-1] = out[-1].replace(" (hO : GridOpen k Ext)", "").replace(
        ", given the open obligations. -/", ". -/")
  out[-1] = out[-1].replace("PRE", "(grid_pre k hk Ext)" if "grid_pre" in CONV else "hO.pre").replace(
      "POST", "(grid_post k hk Ext)" if "grid_post" in CONV else "hO.post")
  out.append("  rcases hl with " + " | ".join(["rfl"] * len(labs)))
  for l, s in zip(labs, suf):
    if s in PROVED:
      n, a = PROVED[s]
      out.append(f"  · exact {n} {a} blk hblk")
    else:
      c = CALLEE[s][1] + " " if s in CALLEE else ""
      out.append(f"  · exact hO.{s} {c}x ra t₀ blk hblk")
  out.append("")
  out.append("end Kraken.Examples.Sbr.Grid")
  txt = "\n".join(out)
  if not nopen:
    txt = txt.replace("""The obligations proved so far are used
directly; the open ones are the fields of `GridOpen` (with the entry and exit conversions
`pre`/`post`). The""", """Every obligation is proved: the blocks
in `GridBlk*`/`GridTrap`/`GridSh*`, the entry and exit conversions `grid_pre`/`grid_post`.
The""")
    txt = txt.replace("\n\n\n/-- `read_sbr_grid` meets", "\n\n/-- `read_sbr_grid` meets")
  print(txt)


main()
