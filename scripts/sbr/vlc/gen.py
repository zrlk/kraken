#!/usr/bin/env python3
"""Generates Kraken/X64/Examples/Sbr/Parse/VlcData.lean: the twenty Huffman tables the SBR
and PS parsers read (`ff_aac_sbr_vlc[10]`, `vlc_ps[10]`), as FFmpeg's start-up code builds
them.

The tables are not data of the object: `init_sbr_tables` (libavcodec/aac/aacdec_tab.c) and
`ff_ps_init_common` (libavcodec/aacps_common.c) fill them at start-up with
`ff_vlc_init_tables_from_lengths`. harness.c runs exactly those two loops, compiled against
the FFmpeg tree given here (its own libavcodec/vlc.c and constant code tables), and prints
the tables; this script turns them into Lean.

usage: gen.py FFMPEG_SRC [-I DIR]... [--out FILE] [--check]
  FFMPEG_SRC  an FFmpeg n8.1 source tree with a config.h (as used to build the objects)
  -I DIR      extra include directories (if the tree's headers include each other by
              another prefix)
  --check     compare with the existing output file instead of writing it
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "../../.."))
OUT = os.path.join(ROOT, "Kraken/X64/Examples/Sbr/Parse/VlcData.lean")


def sbr_block(src):
  text = open(os.path.join(src, "libavcodec/aac/aacdec_tab.c")).read()
  a = text.index("static const uint8_t sbr_huffman_tab[][2]")
  b = text.index("sbr_vlc_offsets[10]", a)
  b = text.index("};", b) + 2
  return text[a:b] + "\n"


def run_harness(src, incs):
  with tempfile.TemporaryDirectory() as d:
    open(os.path.join(d, "sbr_data.inc"), "w").write(sbr_block(src))
    exe = os.path.join(d, "harness")
    cmd = ["cc", "-O1", "-w", "-I", d, "-I", src] + sum((["-I", i] for i in incs), []) + [
        os.path.join(HERE, "harness.c"), "-o", exe]
    subprocess.run(cmd, check=True)
    out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
  tabs = {}
  for line in out.splitlines():
    f = line.split()
    assert f[0] == "T"
    es = [int(x, 16) for x in f[4:]]
    assert len(es) == 4 * int(f[3])
    tabs[(f[1], int(f[2]))] = es
  return tabs


def lean_nat(es):
  """The bytes as one natural number, byte `k` at bits `8k .. 8k + 7`."""
  return "0x" + "".join("%02x" % b for b in reversed(es))


def render(tabs):
  o = []
  o.append("""/-!
# The Huffman tables of the SBR and PS parsers (generated)

Generated by `scripts/sbr/vlc/gen.py`; do not edit. The twenty `VLCElem` tables (`int16_t sym;
int16_t len;`, 4 bytes per entry, little-endian) that FFmpeg n8.1's start-up code builds with
`ff_vlc_init_tables_from_lengths` from its constant code tables: `ff_aac_sbr_vlc[0..9]`
(`init_sbr_tables`, `libavcodec/aac/aacdec_tab.c`, 9 index bits) and `vlc_ps[0..9]`
(`ff_ps_init_common`, `libavcodec/aacps_common.c`, 9 index bits for `0..5`, 5 for `6..9`).
They are not data of the object; `gen.py` runs FFmpeg's own `vlc.c` on its own code tables
to obtain them.

Each table is one natural number holding its bytes (byte `k` at bits `8 k .. 8 k + 7`), with
its number of entries `…E` (the table has `4 * …E` bytes).
-/

namespace Kraken.Examples.Sbr.VlcData
""")
  for (st, k), es in sorted(tabs.items()):
    name = "ff_aac_sbr_vlc" if st == "sbr" else "vlc_ps"
    o.append(f"/-- `{name}[{k}]`: {len(es) // 4} entries. -/")
    o.append(f"def {st}{k}E : Nat := {len(es) // 4}\n")
    o.append(f"/-- The bytes of `{name}[{k}]`. -/")
    o.append(f"def {st}{k} : Nat :=\n  {lean_nat(es)}\n")
  o.append("end Kraken.Examples.Sbr.VlcData\n")
  return "\n".join(o)


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("src")
  ap.add_argument("-I", dest="incs", action="append", default=[])
  ap.add_argument("--out", default=OUT)
  ap.add_argument("--check", action="store_true")
  a = ap.parse_args()
  text = render(run_harness(a.src, a.incs))
  if a.check:
    same = os.path.exists(a.out) and open(a.out).read() == text
    print("vlc: " + ("same" if same else "DIFFERS"))
    sys.exit(0 if same else 1)
  open(a.out, "w").write(text)
  print("wrote", a.out)


if __name__ == "__main__":
  main()
