#!/usr/bin/env python3
"""Generate `KrakenSbrReal/RealData.lean`: the proved texts as the linked binary
places them.

usage: gen.py BINARY LEANDIR OUT.lean
  BINARY   the FFmpeg 8.1 `ffmpeg` PIE (see ../README.md, "The binary")
  LEANDIR  the texts printed by tv/Export.lean (tv.sh leaves them in $SBR_OUT/tv/lean)

For each text of `real_lib.TEXTS`: its entry address (the binary's symbol, in the right
STT_FILE scope), and the size of each of its cells: 0 for a label, else the length of the
binary instruction it meets (cells meet the binary's instructions one to one from the entry,
as tv.py matches them against the objects). Every label a text refers to but does not
define (constants, strings, callees, `_GLOBAL_OFFSET_TABLE_`), and every label of
`STMT_LABELS`, is placed at the address the binary's own instructions encode for it; all
references to one label must agree. The image runs from the lowest to the highest of these
addresses, in address order: texts, one `[label, byteArray]` piece per such label (its cell
spans the bytes up to the next piece), and a labelled gap piece behind each text.
`check.py` re-derives all of it from the elaborated Lean image and the binary.
"""
import hashlib
import os
import sys

import real_lib as R


def build(binary, leandir, work):
  B = R.Binary(binary, work)
  texts, ext = [], {}
  defined = set()
  cells_of = {}
  for name, entry, scope in R.TEXTS:
    cells_of[name] = R.read_export(leandir, name)
    defined |= {c[1] for c in cells_of[name] if c[0] == "label"}
  for name, entry, scope in R.TEXTS:
    cells = cells_of[name]
    assert cells[0] == ("label", entry), (name, cells[0])
    start = B.sym(entry, scope)["value"]
    ninsn = sum(1 for c in cells if c[0] == "insn")
    # enough bytes for the instructions (x86 instructions are at most 15 bytes)
    bins = B.disasm(start, start + 15 * ninsn + 16)
    sizes, k = [], 0
    for kind, txt in cells:
      if kind == "label":
        sizes.append(0)
        continue
      a, bt = bins[k]
      size = bins[k + 1][0] - a
      sizes.append(size)
      for (l, off, rk) in R.refs(txt):
        if l in defined:
          continue
        t = R.target_of(rk, bt)
        if t is None:
          sys.exit(f"gen: {name} {a:#x}: cannot read the target of `{txt}` from `{bt}`")
        ext.setdefault(l, []).append((rk, t - off, a, txt))
      k += 1
    end = bins[k][0]
    texts.append(dict(name=name, entry=entry, start=start, end=end, sizes=sizes))
  # resolve: the GOT first (lea [rip+GOT]), then GOTOFF immediates relative to it
  addr = {}
  for l, rs in ext.items():
    for rk, t, a, txt in rs:
      if rk == "gotoff":
        continue
      addr.setdefault(l, set()).add(t)
  got = addr.get(R.GOT)
  for l, rs in ext.items():
    for rk, t, a, txt in rs:
      if rk == "gotoff":
        if not got or len(got) != 1:
          sys.exit("gen: GOTOFF reference without a unique _GLOBAL_OFFSET_TABLE_")
        addr.setdefault(l, set()).add((next(iter(got)) + t) % 2 ** 64)
  bad = {l: v for l, v in addr.items() if len(v) != 1}
  if bad:
    sys.exit(f"gen: labels with several addresses: { {l: [hex(x) for x in v] for l, v in bad.items()} }")
  addr = {l: next(iter(v)) for l, v in addr.items()}
  missing = [l for l in R.STMT_LABELS if l not in addr and l not in defined]
  if missing:
    sys.exit(f"gen: statement labels not referenced by any text: {missing}")
  # pieces in address order
  items = [(t["start"], 1, ("txt", i)) for i, t in enumerate(texts)]
  items += [(a, 0, ("dat", l)) for l, a in addr.items()]
  items.sort(key=lambda x: (x[0], x[1], str(x[2])))
  pieces = []
  for j, (a, _, (kind, v)) in enumerate(items):
    nxt = items[j + 1][0] if j + 1 < len(items) else None
    if kind == "dat":
      n = (nxt - a) if nxt is not None else 0
      pieces.append(("dat", v, n, a))
    else:
      t = texts[v]
      pieces.append(("txt", v, None, a))
      if nxt is not None:
        if t["end"] > nxt:
          sys.exit(f"gen: text {t['name']} ({a:#x}..{t['end']:#x}) overlaps the next piece at {nxt:#x}")
        if t["end"] < nxt:
          pieces.append(("dat", f"gap_{t['end']:x}", nxt - t["end"], t["end"]))
  return B, texts, addr, pieces


def emit(binary, texts, pieces, out):
  sha = hashlib.sha256(open(binary, "rb").read()).hexdigest()
  start = pieces[0][3]
  L = []
  L.append("/-!\n# The proved texts as the linked binary places them (generated)\n")
  L.append("Generated by `scripts/sbr/real/gen.py` from the FFmpeg 8.1 `ffmpeg` PIE (opt build) with")
  L.append(f"sha256 `{sha}`")
  L.append("and the texts of `scripts/sbr/tv/Export.lean`. Do not edit; `scripts/sbr/real/check.sh`")
  L.append("checks it against the binary. `Real.lean` builds the image from it.\n-/\n")
  L.append("namespace Kraken.Examples.Sbr.Real\n")
  L.append(f"/-- The link-time address of the first cell of the image. -/\ndef rStart : Nat := {start:#x}\n")
  L.append("/-- Per text of `rTexts` (in its order): the size of each cell (0 for a label, else the")
  L.append("length of the binary's instruction at that cell). -/")
  L.append("def rTextSizes : List (List Nat) := [")
  for i, t in enumerate(texts):
    sep = "," if i + 1 < len(texts) else "]"
    body = ", ".join(str(s) for s in t["sizes"])
    L.append(f"  -- {t['name']} @ {t['start']:#x} .. {t['end']:#x}")
    L.append(f"  [{body}]{sep}")
  L.append("")
  L.append("/-- The image in address order: `.inl (l, n)` is the label `l` followed by a cell of")
  L.append("`n` bytes (no cell if `n = 0`); `.inr i` is the `i`-th text of `rTexts`. -/")
  L.append("def rPieces : List ((String × Nat) ⊕ Nat) := [")
  for j, (kind, v, n, a) in enumerate(pieces):
    sep = "," if j + 1 < len(pieces) else "]"
    if kind == "dat":
      L.append(f"  .inl (\"{v}\", {n}){sep}  -- {a:#x}")
    else:
      L.append(f"  .inr {v}{sep}  -- {a:#x} {texts[v]['name']}")
  ai = [j for j, p in enumerate(pieces) if p[0] == "txt" and texts[p[1]]["name"] == "ff_aac_sbr_apply"]
  L.append("\n/-- The position of `ff_aac_sbr_apply`'s text among `rPieces`. -/")
  L.append(f"def rApplyIdx : Nat := {ai[0]}")
  fi = next(j for j, p in enumerate(pieces) if p[0] == "txt")
  L.append("\n/-- The number of pieces below the first text (all of them labels with their cells). -/")
  L.append(f"def rDataN : Nat := {fi}")
  L.append("\nend Kraken.Examples.Sbr.Real\n")
  open(out, "w").write("\n".join(L) + "\n")


def main():
  if len(sys.argv) != 4:
    sys.exit(__doc__)
  binary, leandir, out = sys.argv[1:]
  work = os.path.join(os.path.dirname(os.path.abspath(out)), ".real-work") \
      if not os.environ.get("REAL_WORK") else os.environ["REAL_WORK"]
  B, texts, addr, pieces = build(binary, leandir, work)
  emit(binary, texts, pieces, out)
  print(f"gen: {len(texts)} texts, {len(addr)} labels, {len(pieces)} pieces -> {out}")


if __name__ == "__main__":
  main()
