#!/usr/bin/env python3
"""Generate `big.w`, a synthetic scc program whose `.text` exceeds 64 KiB.

Untrusted test input for the P2b granule layout (`granule_check.py`).  The
program is built to exercise the cases the granule pass and the block-split
pass (`Scc.Lower.splitFunc`) must handle:

* `line0` .. `line{LINES-1}`: long straight-line functions, one IR block each,
  far over `Scc.IR.maxBlockLen` (512 weight units), so the split pass cuts
  their entry blocks;
* `arm`: an `if n = 0 then ... else ...` whose `then` arm is a long
  straight-line block, so a split happens inside a non-entry block;
* `mb`: a routine of many blocks (`MB_DEPTH` nested `if`s, each `then` arm a
  straight-line chain of `MB_ARM` operations): 82 KiB on x64 and 55 KiB on
  AArch64, placed so that a granule boundary falls inside it on both ISAs.

With the defaults `.text` is 218 KiB on x64 (granule boundaries in `line1`,
`arm` and `mb`) and 148 KiB on AArch64 (boundaries in `line3` and `mb`),
measured on today's emitter, which neither aligns `.text` nor splits blocks.
`main` folds every result into a byte; the generator evaluates the program
itself (wrapping U64 arithmetic) and writes the expected exit status to
`big.code`.

Usage: gen_big.py [OUTDIR]           write big.w and big.code (default: the
                                     directory of this script)
       gen_big.py --check [OUTDIR]   regenerate in memory and compare with the
                                     checked-in files; exit 1 on a difference
"""

import os
import sys

LINES = 4          # number of long straight-line functions
LINE_OPS = 1200    # operations per straight-line function
ARM_OPS = 800      # operations in arm's long `then` block
MB_DEPTH = 80      # nested `if`s in the many-block routine (line length <= 120)
MB_ARM = 40        # operations in each of its `then` blocks

MASK = (1 << 64) - 1
OPS = ["mul", "xor", "add", "sub"]


def apply(op, a, b):
    if op == "mul":
        return (a * b) & MASK
    if op == "xor":
        return a ^ b
    if op == "add":
        return (a + b) & MASK
    return (a - b) & MASK


def chain(seed, n, start, indent, pre=""):
    """Lines of a straight-line chain from variable `start`, and the function
    computing its value.  Constants are odd so `mul` stays invertible."""
    lines = []
    steps = []
    prev = start
    for i in range(n):
        c = (seed * 1000003 + i * 7919 + 1) & 0xFFFF | 1
        op = OPS[(seed + i) % len(OPS)]
        lines.append(f"{indent}let {pre}c{i} = cvt U64 {c}")
        lines.append(f"{indent}let {pre}v{i} = fop {op} {prev} {pre}c{i}")
        steps.append((op, c))
        prev = f"{pre}v{i}"

    def run(x):
        for op, c in steps:
            x = apply(op, x, c)
        return x
    return lines, prev, run


def gen():
    out = ["-- Generated by Spike/Tools/gen_big.py; do not edit.  A synthetic",
           "-- program whose .text exceeds 64 KiB (see the generator's docstring).",
           ""]
    runs = []
    for j in range(LINES):
        body, last, run = chain(j + 1, LINE_OPS, "x", "  ")
        out.append(f"def line{j}(x : U64) : U64 =")
        out += body
        out.append(f"  ret {last}")
        out.append("")
        runs.append(run)

    body, last, arm_run = chain(LINES + 1, ARM_OPS, "x", "    ")
    out.append("def arm(x : U64) : U64 =")
    out.append("  let z = cvt U64 0")
    out.append("  let c = fcmp eq x z")
    out.append("  if c = 1 then")
    out += body
    out.append(f"    ret {last}")
    out.append("  else")
    out.append("    ret x")
    out.append("")

    out.append("def mb(x : U64) : U64 =")
    arms = []
    for i in range(MB_DEPTH):
        ind = " " * (i + 1)
        out += [f"{ind}let k{i} = cvt U64 {i + 1}",
                f"{ind}let c{i} = fcmp lt x k{i}",
                f"{ind}if c{i} = 1 then"]
        body, last, run = chain(100 + i, MB_ARM, f"k{i}", ind + " ", f"a{i}_")
        out += body
        out += [f"{ind} ret {last}", f"{ind}else"]
        arms.append(run)
    out.append(" " * (MB_DEPTH + 1) + "ret x")
    out.append("")

    def mb_run(x):
        for i in range(MB_DEPTH):
            if x < i + 1:
                return arms[i](i + 1)
        return x

    # main: r = line_{L-1}(... line0(5)); a = arm(0); m = mb(r & 63);
    # exit (r ^ a ^ m) & 255.
    out.append("def main(u : Unit) : Int =")
    out.append("  let r0 = cvt U64 5")
    r = 5
    for j in range(LINES):
        out.append(f"  let r{j + 1} = line{j}(r{j})")
        r = runs[j](r)
    out.append("  let z = cvt U64 0")
    out.append("  let a = arm(z)")
    a = arm_run(0)
    out.append("  let lo = cvt U64 63")
    out.append(f"  let x = fop and r{LINES} lo")
    out.append("  let m = mb(x)")
    m = mb_run(r & 63)
    out.append(f"  let t = fop xor r{LINES} a")
    out.append("  let s = fop xor t m")
    out.append("  let b = cvt U64 255")
    out.append("  let e = fop and s b")
    out.append("  let i = toInt e")
    out.append("  ret i")
    code = (r ^ a ^ m) & 255
    return "\n".join(out) + "\n", code


def main():
    args = sys.argv[1:]
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    outdir = args[0] if args else os.path.dirname(os.path.abspath(__file__))
    text, code = gen()
    want = {"big.w": text, "big.code": f"{code}\n"}
    if check:
        bad = []
        for name, content in want.items():
            path = os.path.join(outdir, name)
            try:
                with open(path) as f:
                    got = f.read()
            except FileNotFoundError:
                got = None
            if got != content:
                bad.append(name)
        if bad:
            print(f"gen_big.py --check: {', '.join(bad)} differ from the generator; rerun gen_big.py")
            sys.exit(1)
        print("gen_big.py --check: big.w and big.code are up to date")
        return
    for name, content in want.items():
        with open(os.path.join(outdir, name), "w") as f:
            f.write(content)


if __name__ == "__main__":
    main()
