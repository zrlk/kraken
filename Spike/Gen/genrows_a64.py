#!/usr/bin/env python3
"""Classify the instructions of scc's AArch64 listing that no block covers,
and list the source nodes, for a program's per-node instance
(`Spike/Lib/Rows.lean`).

`scc --code` tables the program's blocks (`<name>T`, `List Grp`); every
other instruction of `.text` is a node of its own. This script emits, for
those instructions:

- `<name>R : List Grp`: each as a one-instruction block at its label and
  offset, in program order, so that `blocksIn <name>Prog <name>R` (checked
  by `kernel_rfl`) gives `CodeAt` at every node as for the blocks;
- `<name>Rows : List Row`: its function, label, offset, kind (`RowK`) and
  whether the function is the runtime's;
- `<name>Src : List (String × String)`: the source nodes (`scc --blocks`'
  placement data: block starts and call return points of the compiled
  functions), where the source control can change and the environment must
  be placed;
- a coverage check: the blocks' and the rows' instructions are all of the
  program's, each once.

Kinds: `label` (`adrp Xd, L`; `add Xd, Xs, :lo12:L`), `system` (`nop`,
`msr`, `mrs`), `site` (the `nop` at `scc_rt_take_site` or
`scc_rt_release_site`), `switch` (a register operation writing `sp` from a
register the block offsets do not know: `sw_nd`), `svc`, `load` (`ldr`/`ldar` not off `sp`), `store`
(`str`/`stlr` not off `sp`), `rmw` (`ldadd*`, `swp*`, `cas*`), `other`
(anything else: the script fails, so a new instruction shape is noticed).

Usage: genrows_a64.py NAME LISTING.s CODE.lean PLACE.lean OUT.lean CODEMOD
  NAME        the program's name in CODE.lean (`<name>Prog`, `<name>T`)
  LISTING.s   scc's AArch64 listing (scc --arch arm -S prog.w)
  CODE.lean   scc --code's output for the same program
  PLACE.lean  scc --blocks' placement data (`b.place.lean`)
  OUT.lean    the generated module
  CODEMOD     the module CODE.lean is pasted as (imported by OUT.lean)

Python 3, standard library only; deterministic (program order throughout).
"""
import re
import sys

name, listing, codef, placef, out, codemod = sys.argv[1:7]
code = open(codef).read()
place = open(placef).read()

LAB = r'[.A-Za-z_][\w.]*'

# The blocks of the `--code` tables: (label, offset) of every covered instruction.
covered = set()
for g in re.finditer(r'⟨"(' + LAB + r')", \[(.*?)\]⟩', code, re.S):
    lab = g.group(1)
    for b in re.finditer(r'\((\d+), parseAArch64\("(.*?)"\)\)', g.group(2), re.S):
        off = int(b.group(1))
        for i in range(len(b.group(2).split('\n'))):
            key = (lab, off + i)
            assert key not in covered, f'block instruction twice: {key}'
            covered.add(key)


def kind(fn, lab, ins):
    mn = ins.split()[0]
    m = re.fullmatch(r'(ldr|ldar|str|stlr) (x\d+|xzr), \[(\w+)(, #-?\d+)?\]', ins)
    if m and m.group(3) not in ('sp',):
        return 'load' if m.group(1) in ('ldr', 'ldar') else 'store'
    if re.fullmatch(r'adrp x\d+, ' + LAB, ins) or re.fullmatch(r'add x\d+, x\d+, :lo12:' + LAB, ins):
        return 'label'
    if mn == 'nop':
        return 'site' if lab in ('scc_rt_take_site', 'scc_rt_release_site') else 'system'
    if mn in ('msr', 'mrs'):
        return 'system'
    if re.fullmatch(r'(add|sub) sp, x\d+, #\d+', ins):
        return 'switch'
    if ins == 'svc #0':
        return 'svc'
    if re.match(r'(ldadd|swp|cas)', mn):
        return 'rmw'
    return 'other'


rows = []      # (fn, label, offset, kind, instruction)
total = 0
fn = None
lab = None
idx = 0
section = '.text'
for line in open(listing).read().split('\n'):
    s = line.strip()
    if not s or s.startswith('//'):
        continue
    if s in ('.text', '.data', '.bss') or s.startswith('.section'):
        section = s
        continue
    if section != '.text':
        continue
    m = re.fullmatch(r'\.type (' + LAB + r'), %function', s)
    if m:
        fn = m.group(1)
        continue
    if re.fullmatch(LAB + ':', s):
        lab = s[:-1]
        idx = 0
        if fn is None:
            fn = lab
        continue
    if s.startswith('.'):
        continue
    total += 1
    if (lab, idx) not in covered:
        k = kind(fn, lab, s)
        if k == 'other':
            sys.exit(f'unclassified instruction outside the blocks: {lab}+{idx}: {s}')
        rows.append((fn, lab, idx, k, s))
    idx += 1

if total != len(covered) + len(rows):
    sys.exit(f'coverage: {total} instructions, {len(covered)} in blocks, {len(rows)} rows')

# The source nodes: per compiled function, its nodes' labels.
src = []
for m in re.finditer(r'def (\w+)_label : \w+ → String\n((?:  \| \.\w+ => "[^"]*"\n)+)', place):
    for n in re.finditer(r'=> "([^"]*)"', m.group(2)):
        src.append((m.group(1), n.group(1)))

o = []
o.append(f'''import Spike.Lib.Rows
import {codemod}

/-!
# The nodes of `{name}.w`'s AArch64 code outside its blocks

Generated by `Spike/Gen/genrows_a64.py` from scc's listing, `scc --code`'s
block tables (`{name}T`) and `scc --blocks`' placement data. Every
instruction of `.text` is in a block of `{name}T` or a row here, once
(checked by the generator: {total} instructions, {len(covered)} in blocks,
{len(rows)} rows).

- `{name}R`: each row's instruction as a one-instruction block at its label
  and offset; `{name}R_in` checks them against `{name}Prog` (`blocksIn`), so
  every row has `CodeAt` at its pc (`codeAt_of_blocksIn`).
- `{name}Rows`: each row's function, label, offset, kind and runtime flag
  (`Spike.Lib.Rows.Row`).
- `{name}Src`: the source nodes (function, label), where the source control
  can change.
-/

namespace SccCode

open Kraken Kraken.Promising.AArch64 Kraken.AArch64.Parser Scc.Cert.Rt.A64 Spike.Lib.Rows

/-- The instructions outside the blocks, one per block, in program order. -/
def {name}R : List Grp := [''')
groups = []
for (f, l, i, k, s) in rows:
    if groups and groups[-1][0] == l:
        groups[-1][1].append((i, s, k))
    else:
        groups.append((l, [(i, s, k)]))
gl = []
for (l, items) in groups:
    bs = ',\n    '.join(f'({i}, parseAArch64("{s}")) /- {k} -/' for (i, s, k) in items)
    gl.append(f'  ⟨"{l}", [{bs}]⟩')
o.append(',\n'.join(gl))
o.append(f''']

theorem {name}R_in : blocksIn {name}Prog {name}R := by kernel_rfl

/-- Each row's function, label, offset, kind and whether the function is
the runtime's (`scc_rt_*`, `_start`). -/
def {name}Rows : List Row := [''')
o.append(',\n'.join(
    f'  ⟨"{f}", "{l}", {i}, .{k}, {"true" if (f.startswith("scc_rt_") or f == "_start") else "false"}⟩'
    for (f, l, i, k, s) in rows))
o.append(f''']

-- The rows and the table agree on the places.
#guard {name}Rows.map (fun r => (r.l, r.k)) = {name}R.flatMap fun g => g.bs.map fun b => (g.l, b.1)

-- The blocks' and the rows' instructions number the program's.
#guard ({name}T ++ {name}R).foldl (fun n g => g.bs.foldl (fun n b => n + b.2.length) n) 0 =
  ({name}Prog.filter Scc.Cert.Rt.A64.isIns).length

/-- The source nodes: each compiled function's block starts and call return
points (`scc --blocks`' placement data). -/
def {name}Src : List (String × String) := [''')
o.append(',\n'.join(f'  ("{f}", "{l}")' for (f, l) in src))
o.append(''']

end SccCode
''')
open(out, 'w').write('\n'.join(o))
print(f'{total} instructions: {len(covered)} in blocks, {len(rows)} rows, {len(src)} source nodes')
